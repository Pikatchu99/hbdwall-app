export function getWallSeedMessage(
  birthdayDate: Date,
  locale: string
): { content: string; authorName: string } {
  const lang = MESSAGES[locale] ? locale : 'fr'
  const pool = MESSAGES[lang]

  const today = new Date()
  today.setHours(0, 0, 0, 0)
  const bday = new Date(birthdayDate)
  bday.setHours(0, 0, 0, 0)

  const messages = bday > today ? pool.advance : pool.today
  const content = messages[Math.floor(Math.random() * messages.length)]

  return { content, authorName: '✦' }
}
